from __future__ import annotations

import pytest

from ca9.analysis.ast_scanner import (
    _parse_dependency_requirement,
    discover_declared_dependency_inventory,
    discover_requirement_hashes,
    requirement_file_lines,
)
from ca9.analyzers.supply_chain import analyze_supply_chain
from ca9.inventory import build_inventory

SHA_A = "sha256:" + "a" * 64
SHA_B = "sha256:" + "b" * 64


@pytest.mark.parametrize(
    "requirement",
    [
        f"requests==2.31.0 --hash={SHA_A}",
        f"requests==2.31.0 --hash {SHA_A}",
        f"requests==2.31.0 --hash={SHA_A} --hash={SHA_B}",
        f"requests == 2.31.0 ; python_version >= '3.8' --hash={SHA_A}",
        "requests==2.31.0 --config-settings=editable_mode=compat",
    ],
)
def test_per_requirement_options_keep_the_pinned_version(requirement):
    assert _parse_dependency_requirement(requirement) == ("requests", "2.31.0")


def test_requirement_file_lines_join_continuations_like_pip():
    text = (
        "requests==2.31.0 \\\n"
        f"    --hash={SHA_A} \\\n"
        f"    --hash={SHA_B}\n"
        "# a comment ending in a backslash does not continue \\\n"
        "urllib3==2.0.7\n"
        "    # indented comment \\\n"
        "idna==3.7  # trailing comment\n"
        "pkg @ https://example.invalid/pkg-1.0.tar.gz#sha256=abc\n"
    )

    assert requirement_file_lines(text) == [
        f"requests==2.31.0     --hash={SHA_A}     --hash={SHA_B}",
        "urllib3==2.0.7",
        "idna==3.7",
        "pkg @ https://example.invalid/pkg-1.0.tar.gz#sha256=abc",
    ]


def test_hash_pinned_requirements_keep_versions_and_hashes(tmp_path):
    (tmp_path / "requirements.txt").write_text(
        "# generated by pip-compile --generate-hashes\n"
        "requests==2.31.0 \\\n"
        f"    --hash={SHA_A} \\\n"
        f"    --hash={SHA_B}\n"
        "    # via -r requirements.in\n"
        f"urllib3==2.0.7 --hash={SHA_A}\n"
        "-c constraints.txt\n"
    )
    (tmp_path / "constraints.txt").write_text(f"idna==3.7 \\\n    --hash={SHA_B}\n")

    inventory = discover_declared_dependency_inventory(tmp_path)
    hashes = discover_requirement_hashes(tmp_path)

    assert inventory == {
        "requests": ("requests", "2.31.0"),
        "urllib3": ("urllib3", "2.0.7"),
    }
    assert hashes["requests"] == (SHA_A, SHA_B)
    assert hashes["urllib3"] == (SHA_A,)


def test_inventory_records_requirement_hashes(tmp_path):
    (tmp_path / "requirements.txt").write_text(
        f"requests==2.31.0 \\\n    --hash={SHA_A}\n"
        f"pkg @ https://example.invalid/pkg-1.0.tar.gz \\\n    --hash={SHA_B}\n"
        "plain @ https://example.invalid/plain-1.0.tar.gz\n"
    )

    packages = {package.name: package for package in build_inventory(tmp_path).packages}

    assert packages["requests"].version == "2.31.0"
    assert packages["requests"].metadata["hashes"] == [SHA_A]
    assert packages["pkg"].artifacts[0].hash == SHA_B
    assert packages["plain"].artifacts[0].hash is None
    missing = {
        finding.metadata["package"]
        for finding in analyze_supply_chain(build_inventory(tmp_path))
        if finding.signal_type == "missing_artifact_hash"
    }
    assert missing == {"plain"}


def test_index_url_applies_to_hash_pinned_requirements(tmp_path):
    (tmp_path / "requirements.txt").write_text(
        "--index-url https://packages.example.invalid/simple\n"
        f"requests==2.31.0 \\\n    --hash={SHA_A}\n"
    )

    package = next(
        package for package in build_inventory(tmp_path).packages if package.name == "requests"
    )

    assert package.source_registry == "https://packages.example.invalid/simple"
